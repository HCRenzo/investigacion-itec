"""Performance evaluation: percentile latencies from real orders, a live benchmark and empirical complexity."""
import time
from decimal import Decimal

from sqlalchemy import select

from api.config import Settings
from api.models import Order
from api.repositories.order import OrderRepository
from api.services import stats
from api.services.experiment_service import ExperimentService
from api.services.receipt import OrderLine, ReceiptEngineFactory
import random


class PerformanceService:
    def __init__(self, orders: OrderRepository, settings: Settings):
        self.orders = orders
        self.settings = settings

    def order_latencies(self) -> list[dict]:
        """Latency distribution of the receipts really generated by the store, per engine."""
        rows = self.orders.session.execute(
            select(Order.engine, Order.processing_seconds).where(Order.deleted_at.is_(None))).all()
        by_engine: dict[str, list[float]] = {}
        for engine, seconds in rows:
            by_engine.setdefault(engine, []).append(float(seconds or 0))
        return [{"engine": e, "n": len(v), "mean": stats.mean(v), "sd": stats.stdev(v), "min": min(v),
                 "p50": stats.percentile(v, 50), "p90": stats.percentile(v, 90), "p95": stats.percentile(v, 95),
                 "p99": stats.percentile(v, 99), "max": max(v)} for e, v in sorted(by_engine.items())]

    def benchmark(self, *, sizes: list[int], repetitions: int, v1_work_factor: int, catalog_size: int, seed: int) -> dict:
        """Throughput and scaling of both engines for growing order sizes, plus the empirical complexity exponent."""
        sizes = sorted(set(sizes))
        catalog = ExperimentService.make_catalog(catalog_size)
        rng = random.Random(seed)
        points = []
        for n in sizes:
            order = ExperimentService.make_order(rng, n, catalog_size)
            row = {"lines": n}
            for name in ("v1", "v2"):
                settings = Settings(**{**self.settings.__dict__, "legacy_work_factor": v1_work_factor,
                                       "legacy_target_seconds": None})
                engine = ReceiptEngineFactory(settings).create(name, Decimal("0.21"))
                engine.calculate(order, catalog)  # warm-up
                samples, started = [], time.perf_counter()
                for _ in range(repetitions):
                    samples.append(engine.calculate(order, catalog).processing_seconds)
                wall = time.perf_counter() - started
                row[name] = {"mean": stats.mean(samples), "p50": stats.percentile(samples, 50),
                             "p95": stats.percentile(samples, 95), "max": max(samples),
                             "throughput": repetitions / wall if wall else None}
            row["speedup"] = row["v1"]["mean"] / row["v2"]["mean"] if row["v2"]["mean"] else None
            points.append(row)
        complexity = {name: stats.loglog_slope(sizes, [p[name]["mean"] for p in points]) for name in ("v1", "v2")}
        return {"points": points, "complexity": complexity,
                "params": {"sizes": sizes, "repetitions": repetitions, "v1_work_factor": v1_work_factor,
                           "catalog_size": catalog_size}}
